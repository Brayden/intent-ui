import { Button } from "@cloudflare/kumo/components/button";
import { Switch } from "@cloudflare/kumo/components/switch";
import { GearSix, MagicWand, Plus } from "@phosphor-icons/react";
import { GeneratedPage, IntentUIProvider, useIntentUI } from "../../../packages/react/src";
import { BillingPage } from "./pages/BillingPage";
import { OverviewPage } from "./pages/OverviewPage";
import { WorkersPage } from "./pages/WorkersPage";
import { go, link, usePathname } from "./router";
import { bindings } from "./bindings";
import { useViews } from "./views";

export function App() {
  return (
    // ⌘⇧K instead of ⌘K, as a host with its own ⌘K menu (like a cloud dashboard) would choose.
    <IntentUIProvider endpoint="/api" components={bindings} shortcut="mod+shift+k">
      <Shell />
    </IntentUIProvider>
  );
}

function NavLink({ href, children }: { href: string; children: React.ReactNode }) {
  const active = usePathname() === href;
  return (
    <a
      href={href}
      onClick={link}
      className={`rounded-md px-3 py-1.5 text-sm no-underline ${active ? "bg-kumo-tint font-medium text-kumo-strong" : "text-kumo-subtle hover:text-kumo-default"}`}
    >
      {children}
    </a>
  );
}

function Shell() {
  const pathname = usePathname();
  const { views, add } = useViews();
  const { mutationsEnabled, setMutationsEnabled, openSettings, openCommandMenu } = useIntentUI();
  const view = /^\/views\/([^/]+)/.exec(pathname)?.[1];

  return (
    <div className="flex min-h-screen">
      <aside className="flex w-56 shrink-0 flex-col gap-1 border-r border-kumo-line p-3">
        <p className="px-3 py-2 font-semibold text-kumo-strong">Acme Cloud</p>
        <NavLink href="/">Overview</NavLink>
        <NavLink href="/workers">Workers</NavLink>
        <NavLink href="/billing">Billing</NavLink>
        <p className="mt-4 px-3 text-xs font-medium tracking-wide text-kumo-subtle uppercase">Your views</p>
        {views.map((v) => (
          <NavLink key={v.id} href={`/views/${v.id}`}>
            {v.title}
          </NavLink>
        ))}
        <Button variant="ghost" size="sm" icon={Plus} className="justify-start" onClick={() => go("/views/new")}>
          New view
        </Button>
      </aside>

      <div className="flex min-w-0 flex-1 flex-col">
        <header className="flex h-14 items-center justify-end gap-4 border-b border-kumo-line px-6">
          {view && view !== "new" && (
            <Button variant="secondary" size="sm" icon={MagicWand} onClick={openCommandMenu}>
              Generate
            </Button>
          )}
          <Switch label="Customizations" checked={mutationsEnabled} onCheckedChange={setMutationsEnabled} />
          <Button variant="secondary" size="sm" icon={GearSix} onClick={openSettings}>
            Intent UI settings
          </Button>
        </header>
        <main className="flex-1 p-6">
          {pathname === "/" ? (
            <OverviewPage />
          ) : pathname === "/workers" ? (
            <WorkersPage />
          ) : pathname === "/billing" ? (
            <BillingPage />
          ) : view === "new" ? (
            // Starts from scratch; once created, the host remembers it and moves to its URL.
            <GeneratedPage
              basePath="/views/new"
              title="Untitled view"
              onCreate={(id) => {
                add({ id, title: `View ${views.length + 1}` });
                window.history.replaceState(null, "", `/views/${id}`);
                window.dispatchEvent(new PopStateEvent("popstate"));
              }}
            />
          ) : view ? (
            <GeneratedPage key={view} basePath={`/views/${view}`} id={view}>
              <p className="text-kumo-subtle">This view is generated by Intent UI. Turn customizations on to see it.</p>
            </GeneratedPage>
          ) : (
            <p className="text-kumo-subtle">Not found.</p>
          )}
        </main>
      </div>
    </div>
  );
}
